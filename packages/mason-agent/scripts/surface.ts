import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import {
	ASSET_TURN_BYTES,
	ASSETS_PER_TURN,
	ATTACHMENT_BYTES,
	ATTACHMENT_LIMIT,
	ATTACHMENT_TTL_MS,
} from "../src/server/attachments.ts";
import { CONNECTOR_PATH } from "../src/server/connector.ts";
import {
	CONNECTOR_CONTROL_LIMIT,
	CONNECTOR_FIRE_LIMIT,
	CONNECTOR_SUBMISSION_LIMIT,
	FIRE_WINDOW_MS,
	JSON_BODY_MAX_BYTES,
} from "../src/server/limits.ts";
import { BASE_EXTENSIONS, MCP_EXTENSION_NAME, PER_BOOT_EXTENSIONS } from "../src/server/runtime.ts";

export const SURFACE_PATH = "docs/SURFACE.md";
export const SERVER_SOURCE = "src/server/main.ts";

export interface Door {
	readonly path: string;
	readonly kind: "public" | "connector";
	readonly why: string;
}

export const DOORS: readonly Door[] = [
	{ path: "/api/health", kind: "public", why: "the liveness probe: one word, so a dead process is distinguishable" },
	{ path: CONNECTOR_PATH, kind: "connector", why: "the connector's Chord socket, authenticated at the upgrade" },
	{
		path: `${CONNECTOR_PATH}/attachments`,
		kind: "connector",
		why: "an upload, authenticated as the connector that posts it",
	},
	{
		path: "/api/connector/assets/",
		kind: "connector",
		why: "one asset's bytes, authenticated and scoped to the connector's grant",
	},
];

export function literalsIn(source: string): string[] {
	const found = new Set<string>();
	for (const match of source.matchAll(/url\.pathname\s*(?:===|!==|startsWith)\s*"([^"]+)"/g)) {
		if (match[1] !== undefined) found.add(match[1]);
	}
	return [...found].sort();
}

export function unclaimed(source: string, doors: readonly Door[] = DOORS): string[] {
	const claimed = new Set(doors.map((door) => door.path));
	return literalsIn(source).filter((path) => !claimed.has(path));
}

export function renderSurface(): string {
	const rows = DOORS.map((door) => `| \`${door.path}\` | ${door.kind} | ${door.why} |`).join("\n");
	const extensions = BASE_EXTENSIONS.map((extension) => extension.name).join(", ");
	const perBoot = PER_BOOT_EXTENSIONS.join(", ");
	const budgets = [
		`${CONNECTOR_SUBMISSION_LIMIT} submissions, ${CONNECTOR_FIRE_LIMIT} fires, ${CONNECTOR_CONTROL_LIMIT} controls and ${ATTACHMENT_LIMIT} attachments a minute per connector`,
		`${JSON_BODY_MAX_BYTES / 1024} KiB of JSON in one call`,
		`${ATTACHMENT_BYTES / 1024 / 1024} MiB a file, kept for ${ATTACHMENT_TTL_MS / 86_400_000} days`,
		`${ASSETS_PER_TURN} files a turn, ${ASSET_TURN_BYTES / 1024 / 1024} MiB in total`,
		`a window of ${FIRE_WINDOW_MS / 1000} s`,
	].join("; ");
	return `<!-- generated by scripts/surface.ts: do not edit this file; run \`npm run gen:surface\` -->

# The surface

What a process may reach, rendered from the code. A door the code serves and this file does not name is a
\`npm run gen:surface:check\` failure, which is the only automated reading of AGENTS.md rule 6. Where a behaviour
goes, as opposed to what exists, is [\`ARCHITECTURE.md\`](ARCHITECTURE.md).

## Doors

One row per way in. There is no browser application and no owner token: a person speaks through a connector, and a
connector presents a credential mason issued for it.

| Path | Opened by | Why |
|---|---|---|
${rows}

## Extensions a boot installs

The base list, in this order: ${extensions}.

Then the ones the boot builds for itself: ${perBoot} always, and \`${MCP_EXTENSION_NAME}\` when an enabled entry has an MCP
server. A per-boot extension owns something that dies with the process — the asset store, a lease directory, a QuickJS
sandbox, one client socket per integration — which is why none of them is a module constant.

The tool list is pinned by the prompt test, because the prompt is where it is announced. No MCP tool schema is ever
in it: a service's tools are reached from a script.

## What a caller may spend

Budgets: ${budgets}.
`;
}

function main(): void {
	const root = fileURLToPath(new URL("..", import.meta.url));
	const repository = fileURLToPath(new URL("../../..", import.meta.url));
	const target = join(repository, SURFACE_PATH);
	const source = readFileSync(join(root, SERVER_SOURCE), "utf8");
	const unclaimedPaths = unclaimed(source);
	if (unclaimedPaths.length > 0) {
		console.error(`[surface] a route in ${SERVER_SOURCE} is in no door list: ${unclaimedPaths.join(", ")}`);
		process.exitCode = 1;
		return;
	}
	const rendered = renderSurface();
	const missing = [...PER_BOOT_EXTENSIONS, MCP_EXTENSION_NAME].filter(
		(name) => !rendered.includes(name === MCP_EXTENSION_NAME ? `\`${name}\`` : name),
	);
	if (missing.length > 0) {
		console.error(`[surface] no row for the per-boot extension(s) ${missing.join(", ")}`);
		process.exitCode = 1;
		return;
	}
	if (process.argv.includes("--check")) {
		const committed = readFileSync(target, "utf8");
		if (committed !== rendered) {
			console.error(`[surface] ${SURFACE_PATH} is stale: run \`npm run gen:surface\``);
			process.exitCode = 1;
			return;
		}
		console.log(`[surface] ${SURFACE_PATH} is up to date`);
		return;
	}
	writeFileSync(target, rendered);
	console.log(`[surface] wrote ${SURFACE_PATH}`);
}

if (process.argv[1]?.endsWith("surface.ts") === true) main();
